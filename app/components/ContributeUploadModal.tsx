"use client";

import { useRef, useState } from "react";
import { Button } from "@/components/ui/button";
import { Upload, FileText, X, Loader2 } from "lucide-react";
import { toast } from "sonner";
import { uploadContribution } from "@/lib/api/contribution.api";

const MAX_BYTES = 50 * 1024 * 1024; // 50 MB — matches the backend limit

function formatSize(bytes: number): string {
  if (bytes < 1024 * 1024) return `${Math.max(1, Math.round(bytes / 1024))} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

/**
 * Turn an axios failure into something a student can act on.
 *
 * A rejection generated by the proxy rather than the API (e.g. nginx's 413 for an
 * oversized body) carries no CORS headers, so the browser blocks it and axios
 * surfaces a bare "Network Error" with no `response`. Reporting that verbatim
 * tells the user nothing, so name the likely causes instead.
 */
function describeUploadError(err: {
  response?: { status?: number; data?: { message?: string } };
  code?: string;
  message?: string;
}): string {
  const apiMessage = err?.response?.data?.message;
  if (apiMessage) return apiMessage;

  if (err?.response?.status === 413) {
    return "This PDF is too large for the server to accept. Please try a smaller file.";
  }
  if (err?.code === "ECONNABORTED") {
    return "The upload timed out. Check your connection and try again.";
  }
  if (!err?.response) {
    return "The upload didn't reach the server — the file may be too large or the connection dropped. Try a smaller PDF, or try again.";
  }
  return err?.message || "Upload failed. Please try again.";
}

export default function ContributeUploadModal({
  open,
  onClose,
  onUploaded,
  code,
  courseTitle,
}: {
  open: boolean;
  onClose: () => void;
  /** Called after a successful upload (or a 409) so the grid can refresh. */
  onUploaded: () => void;
  code: string;
  courseTitle: string;
}) {
  const [file, setFile] = useState<File | null>(null);
  const [note, setNote] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [dragOver, setDragOver] = useState(false);
  const [submitting, setSubmitting] = useState(false);
  const inputRef = useRef<HTMLInputElement>(null);

  if (!open) return null;

  // Validate type + size on the client before doing anything.
  const pickFile = (f: File | null) => {
    setError(null);
    if (!f) return;
    const isPdf =
      f.type === "application/pdf" && f.name.toLowerCase().endsWith(".pdf");
    if (!isPdf) {
      setError("Please select a PDF file.");
      return;
    }
    if (f.size > MAX_BYTES) {
      setError("PDF must be 50 MB or smaller.");
      return;
    }
    setFile(f);
  };

  const reset = () => {
    setFile(null);
    setNote("");
    setError(null);
    setSubmitting(false);
  };

  const handleClose = () => {
    if (submitting) return; // don't drop an in-flight upload
    reset();
    onClose();
  };

  // Awaited (not fire-and-forget) so we know whether this course got claimed and
  // can flip the card / surface a 409 in place.
  const handleSubmit = async () => {
    if (!file) {
      setError("Please choose a PDF to upload.");
      return;
    }

    const form = new FormData();
    form.append("pdf", file);
    if (note.trim()) form.append("note", note.trim());

    setSubmitting(true);
    setError(null);
    try {
      const res = await uploadContribution(code, form);
      toast.success(res.message || "PDF uploaded. Thank you for contributing!");
      reset();
      onUploaded();
      onClose();
    } catch (e) {
      const err = e as {
        response?: { status?: number; data?: { message?: string } };
        code?: string;
        message?: string;
      };
      setError(describeUploadError(err));
      setSubmitting(false);
      // Someone else claimed this course first — refresh so the card locks.
      if (err?.response?.status === 409) onUploaded();
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 px-4">
      <div className="w-full max-w-md space-y-5 rounded-2xl bg-white p-6 shadow-xl">
        <div className="flex items-start justify-between gap-3">
          <div>
            <h2 className="text-xl font-semibold text-blue-900">
              Upload course PDF
            </h2>
            <p className="mt-1 text-sm text-slate-500">
              Contribute the handout or notes for {courseTitle} ({code}). Each
              course accepts one PDF.
            </p>
          </div>
          <button
            onClick={handleClose}
            disabled={submitting}
            aria-label="Close"
            className="shrink-0 rounded-full p-1 text-slate-400 transition-colors hover:bg-slate-100 hover:text-slate-600 disabled:opacity-50"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* Dropzone / file picker */}
        <div
          onClick={() => !submitting && inputRef.current?.click()}
          onDragOver={(e) => {
            e.preventDefault();
            setDragOver(true);
          }}
          onDragLeave={() => setDragOver(false)}
          onDrop={(e) => {
            e.preventDefault();
            setDragOver(false);
            if (!submitting) pickFile(e.dataTransfer.files?.[0] ?? null);
          }}
          className={`flex cursor-pointer flex-col items-center justify-center gap-2 rounded-xl border-2 border-dashed p-6 text-center transition-colors ${
            dragOver
              ? "border-teal-500 bg-teal-50"
              : "border-slate-300 hover:border-teal-400 hover:bg-slate-50"
          } ${submitting ? "pointer-events-none opacity-60" : ""}`}
        >
          {file ? (
            <div className="flex items-center gap-2 text-slate-700">
              <FileText className="h-5 w-5 shrink-0 text-teal-600" />
              <span className="truncate text-sm font-medium">{file.name}</span>
              <span className="shrink-0 text-xs text-slate-400">
                {formatSize(file.size)}
              </span>
            </div>
          ) : (
            <>
              <Upload className="h-6 w-6 text-slate-400" />
              <p className="text-sm font-medium text-slate-600">
                Click to choose or drag a PDF here
              </p>
              <p className="text-xs text-slate-400">PDF only · up to 50 MB</p>
            </>
          )}
        </div>
        <input
          ref={inputRef}
          type="file"
          accept="application/pdf"
          className="hidden"
          onChange={(e) => pickFile(e.target.files?.[0] ?? null)}
        />

        {/* Optional note */}
        <textarea
          value={note}
          onChange={(e) => setNote(e.target.value)}
          maxLength={500}
          rows={2}
          disabled={submitting}
          placeholder="Optional note (e.g. which chapters this covers)"
          className="w-full resize-none rounded-lg border border-slate-300 px-3 py-2 text-sm focus:border-teal-500 focus:outline-none focus:ring-2 focus:ring-teal-200 disabled:opacity-60"
        />

        {error && <p className="text-sm text-red-600">{error}</p>}

        <div className="flex gap-3">
          <Button
            variant="outline"
            onClick={handleClose}
            disabled={submitting}
            className="flex-1"
          >
            Cancel
          </Button>
          <Button
            onClick={handleSubmit}
            disabled={submitting}
            className="flex-1 bg-blue-900 text-white hover:bg-blue-800"
          >
            {submitting ? (
              <>
                <Loader2 className="mr-2 h-4 w-4 animate-spin" />
                Uploading…
              </>
            ) : (
              "Upload"
            )}
          </Button>
        </div>
      </div>
    </div>
  );
}
